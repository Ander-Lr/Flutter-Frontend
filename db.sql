    BEGIN;

    CREATE EXTENSION IF NOT EXISTS pgcrypto;

    -- =============================================
    -- TABLAS BASE (sin dependencias)
    -- =============================================

    CREATE TABLE IF NOT EXISTS public.roles
    (
        id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY ( INCREMENT 1 START 1 MINVALUE 1 MAXVALUE 9223372036854775807 CACHE 1 ),
        name character varying(255) COLLATE pg_catalog."default" NOT NULL,
        CONSTRAINT roles_pkey PRIMARY KEY (id)
    );

    CREATE TABLE IF NOT EXISTS public.empresas
    (
        id_empresa uuid NOT NULL,
        ciudad character varying(80) COLLATE pg_catalog."default",
        correo_contacto character varying(120) COLLATE pg_catalog."default",
        created_at timestamp with time zone DEFAULT now(),
        direccion text COLLATE pg_catalog."default",
        estado_activo boolean DEFAULT true,
        frecuencia_analisis integer,
        industria_objetivo character varying(80) COLLATE pg_catalog."default",
        logo_url text COLLATE pg_catalog."default",
        nombre_empresa character varying(120) COLLATE pg_catalog."default" NOT NULL,
        pais character varying(80) COLLATE pg_catalog."default",
        plan_servicio character varying(50) COLLATE pg_catalog."default",
        prioridad_monitoreo smallint,
        razon_social character varying(150) COLLATE pg_catalog."default",
        ruc character varying(20) COLLATE pg_catalog."default",
        sector character varying(80) COLLATE pg_catalog."default",
        sitio_web text COLLATE pg_catalog."default",
        telefono character varying(30) COLLATE pg_catalog."default",
        updated_at timestamp with time zone DEFAULT now(),
        CONSTRAINT empresas_pkey PRIMARY KEY (id_empresa)
    );

    -- =============================================
    -- USUARIOS (depende de roles y empresas)
    -- =============================================

    CREATE TABLE IF NOT EXISTS public.users
    (
        user_id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY ( INCREMENT 1 START 1 MINVALUE 1 MAXVALUE 9223372036854775807 CACHE 1 ),
        created_at timestamp with time zone DEFAULT now(),
        email character varying(255) COLLATE pg_catalog."default" NOT NULL,
        is_active boolean DEFAULT true,
        last_login timestamp(6) with time zone,
        password_hash character varying(255) COLLATE pg_catalog."default" NOT NULL,
        profile_picture character varying(255) COLLATE pg_catalog."default",
        recovery_token character varying(255) COLLATE pg_catalog."default",
        token_expiration timestamp(6) with time zone,
        updated_at timestamp with time zone DEFAULT now(),
        username character varying(255) COLLATE pg_catalog."default" NOT NULL,
        empresa_id uuid NOT NULL,
        role_id bigint NOT NULL,
        CONSTRAINT users_pkey PRIMARY KEY (user_id),
        CONSTRAINT uk_users_email UNIQUE (email)
    );

    -- =============================================
    -- LOGS y TOKENS (dependen de users)
    -- =============================================

    CREATE TABLE IF NOT EXISTS public.logs
    (
        id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY ( INCREMENT 1 START 1 MINVALUE 1 MAXVALUE 9223372036854775807 CACHE 1 ),
        action text COLLATE pg_catalog."default" NOT NULL,
        "timestamp" timestamp with time zone DEFAULT now(),
        user_id bigint NOT NULL,
        CONSTRAINT logs_pkey PRIMARY KEY (id)
    );

    CREATE TABLE IF NOT EXISTS public.tokens
    (
        id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY ( INCREMENT 1 START 1 MINVALUE 1 MAXVALUE 9223372036854775807 CACHE 1 ),
        created_at timestamp with time zone DEFAULT now(),
        device_info text COLLATE pg_catalog."default",
        expires_at timestamp(6) with time zone NOT NULL,
        ip_address text COLLATE pg_catalog."default",
        revoked boolean DEFAULT false,
        revoked_at timestamp(6) with time zone,
        token text COLLATE pg_catalog."default" NOT NULL,
        user_id bigint NOT NULL,
        CONSTRAINT tokens_pkey PRIMARY KEY (id)
    );

    -- =============================================
    -- CUENTAS SOCIALES (depende de empresas)
    -- =============================================

    CREATE TABLE IF NOT EXISTS public.cuentas_sociales
    (
        id_cuenta_social uuid NOT NULL,

        -- Identidad de la cuenta
        nombre_cuenta character varying(120) COLLATE pg_catalog."default" NOT NULL,
        usuario_handle character varying(120) COLLATE pg_catalog."default",
        img_usuario text COLLATE pg_catalog."default",
        enlace text COLLATE pg_catalog."default",
        descripcion text COLLATE pg_catalog."default",
        summary jsonb,
        -- Ejemplo:
        -- {
        --   "nro_posts": 17,
        --   "seguidores": 849,
        --   "seguidos": 97
        -- }

        -- =============================================
        -- CREDENCIALES — encriptadas con pgcrypto
        -- Escribir: pgp_sym_encrypt(valor::text, clave)
        -- Leer:     pgp_sym_decrypt(campo::bytea, clave)::json
        -- La clave secreta NUNCA se guarda en BD,
        -- se inyecta desde variable de entorno en el backend
        -- =============================================
        credenciales_red_social bytea,
        -- Estructura JSON antes de encriptar:
        -- {
        --   "usuario":  "mariela_mmendoza",
        --   "email":    "seben.sd.11@gmail.com",
        --   "password": "sdf-Lara$"
        -- }

        credenciales_correo_recuperacion bytea,
        -- Estructura JSON antes de encriptar:
        -- {
        --   "email":    "seben.zxc.11@gmail.com",
        --   "password": "dfsdfsdfsdf"
        -- }

        -- Control
        estado_activo boolean DEFAULT true,
        fecha_creacion timestamp with time zone DEFAULT now(),
        empresa_id uuid NOT NULL,

        CONSTRAINT cuentas_sociales_pkey PRIMARY KEY (id_cuenta_social)
    );

    -- =============================================
    -- PUBLICACIONES (depende de cuentas_sociales)
    -- =============================================

    CREATE TABLE IF NOT EXISTS public.publicaciones
    (
        id_publicacion uuid NOT NULL,
        autor character varying(120) COLLATE pg_catalog."default",
        img_autor text COLLATE pg_catalog."default",
        url_publicacion text COLLATE pg_catalog."default",
        fecha_publicacion timestamp(6) with time zone,
        contenido text COLLATE pg_catalog."default",
        hashtags jsonb,
        interacciones jsonb,
        tipo character varying(20) COLLATE pg_catalog."default",                      -- 'foto' | 'video' | 'mixto'
        multimedia jsonb,
        -- ANÁLISIS
        sentimiento character varying(20) COLLATE pg_catalog."default",
        sentimiento_score numeric(5, 4),
        emocion character varying(30) COLLATE pg_catalog."default",
        toxicidad_score numeric(5, 4),
        riesgo_reputacional numeric(5, 4),
        analisis_json jsonb,
        fecha_analisis timestamp with time zone,
        analisis_version character varying(50) COLLATE pg_catalog."default",
        requiere_revision boolean DEFAULT false,
        -- Control
        estado_activo boolean DEFAULT true,
        created_at timestamp with time zone DEFAULT now(),
        updated_at timestamp with time zone DEFAULT now(),
        cuenta_social_id uuid NOT NULL,
        CONSTRAINT publicaciones_pkey PRIMARY KEY (id_publicacion)
    );

    -- =============================================
    -- COMENTARIOS (depende de publicaciones)
    -- =============================================

    CREATE TABLE IF NOT EXISTS public.comentarios
    (
        id_comentario uuid NOT NULL,
        autor character varying(120) COLLATE pg_catalog."default",
        img_autor text COLLATE pg_catalog."default",
        enlace_perfil_autor text COLLATE pg_catalog."default",
        contenido text COLLATE pg_catalog."default",
        multimedia jsonb,
        -- ANÁLISIS
        sentimiento character varying(20) COLLATE pg_catalog."default",
        sentimiento_score numeric(5, 4),
        toxicidad_score numeric(5, 4),
        es_spam boolean DEFAULT false,
        analisis_json jsonb,
        fecha_analisis timestamp with time zone,
        analisis_version character varying(50) COLLATE pg_catalog."default",
        requiere_revision boolean DEFAULT false,
        -- Auto-referencia
        comentario_padre_id uuid,
        -- Control
        estado_activo boolean DEFAULT true,
        created_at timestamp with time zone DEFAULT now(),
        updated_at timestamp with time zone DEFAULT now(),
        publicacion_id uuid NOT NULL,
        CONSTRAINT comentarios_pkey PRIMARY KEY (id_comentario)
    );

    -- =============================================
    -- SCRAPING JOBS
    -- =============================================

    CREATE TABLE IF NOT EXISTS public.scraping_jobs
    (
        id uuid NOT NULL DEFAULT gen_random_uuid(),
        empresa_id uuid NOT NULL,
        user_id bigint NOT NULL,
        cuenta_social_id uuid,
        tipo_tarea character varying(50) NOT NULL,
        target_url text COLLATE pg_catalog."default",
        target_handle character varying(255) COLLATE pg_catalog."default",
        parametros jsonb,
        estado character varying(30) NOT NULL DEFAULT 'PENDING',
        prioridad smallint DEFAULT 5,
        progreso smallint DEFAULT 0,
        intento_actual smallint DEFAULT 0,
        max_intentos smallint DEFAULT 3,
        mensaje_error text COLLATE pg_catalog."default",
        codigo_error character varying(50) COLLATE pg_catalog."default",
        resultado_resumen jsonb,
        created_at timestamp with time zone DEFAULT now(),
        queued_at timestamp with time zone,
        started_at timestamp with time zone,
        finished_at timestamp with time zone,
        worker_id character varying(100) COLLATE pg_catalog."default",
        CONSTRAINT scraping_jobs_pkey PRIMARY KEY (id),
        CONSTRAINT chk_progreso  CHECK (progreso  BETWEEN 0 AND 100),
        CONSTRAINT chk_prioridad CHECK (prioridad BETWEEN 1 AND 10),
        CONSTRAINT chk_estado    CHECK (estado IN ('PENDING','QUEUED','RUNNING','COMPLETED','FAILED','CANCELLED'))
    );

    -- =============================================
    -- ÍNDICES — scraping_jobs
    -- =============================================

    CREATE INDEX IF NOT EXISTS idx_scraping_jobs_estado_prioridad
        ON public.scraping_jobs (estado, prioridad ASC, created_at ASC);

    CREATE INDEX IF NOT EXISTS idx_scraping_jobs_empresa
        ON public.scraping_jobs (empresa_id, created_at DESC);

    CREATE INDEX IF NOT EXISTS idx_scraping_jobs_cuenta
        ON public.scraping_jobs (cuenta_social_id);

    -- =============================================
    -- FOREIGN KEYS
    -- =============================================

    ALTER TABLE IF EXISTS public.users
        ADD CONSTRAINT fk_users_role_id FOREIGN KEY (role_id)
        REFERENCES public.roles (id)
        ON UPDATE NO ACTION ON DELETE RESTRICT;

    ALTER TABLE IF EXISTS public.users
        ADD CONSTRAINT fk_users_empresa_id FOREIGN KEY (empresa_id)
        REFERENCES public.empresas (id_empresa)
        ON UPDATE NO ACTION ON DELETE RESTRICT;

    ALTER TABLE IF EXISTS public.logs
        ADD CONSTRAINT fk_logs_user_id FOREIGN KEY (user_id)
        REFERENCES public.users (user_id)
        ON UPDATE NO ACTION ON DELETE CASCADE;

    ALTER TABLE IF EXISTS public.tokens
        ADD CONSTRAINT fk_tokens_user_id FOREIGN KEY (user_id)
        REFERENCES public.users (user_id)
        ON UPDATE NO ACTION ON DELETE CASCADE;

    ALTER TABLE IF EXISTS public.cuentas_sociales
        ADD CONSTRAINT fk_cuentas_empresa_id FOREIGN KEY (empresa_id)
        REFERENCES public.empresas (id_empresa)
        ON UPDATE NO ACTION ON DELETE RESTRICT;

    ALTER TABLE IF EXISTS public.publicaciones
        ADD CONSTRAINT fk_publicaciones_cuenta_social_id FOREIGN KEY (cuenta_social_id)
        REFERENCES public.cuentas_sociales (id_cuenta_social)
        ON UPDATE NO ACTION ON DELETE RESTRICT;

    ALTER TABLE IF EXISTS public.comentarios
        ADD CONSTRAINT fk_comentarios_publicacion_id FOREIGN KEY (publicacion_id)
        REFERENCES public.publicaciones (id_publicacion)
        ON UPDATE NO ACTION ON DELETE CASCADE;

    ALTER TABLE IF EXISTS public.comentarios
        ADD CONSTRAINT fk_comentario_padre_id FOREIGN KEY (comentario_padre_id)
        REFERENCES public.comentarios (id_comentario)
        ON UPDATE NO ACTION ON DELETE SET NULL;

    ALTER TABLE IF EXISTS public.scraping_jobs
        ADD CONSTRAINT fk_scraping_empresa FOREIGN KEY (empresa_id)
        REFERENCES public.empresas (id_empresa)
        ON UPDATE NO ACTION ON DELETE CASCADE;

    ALTER TABLE IF EXISTS public.scraping_jobs
        ADD CONSTRAINT fk_scraping_user FOREIGN KEY (user_id)
        REFERENCES public.users (user_id)
        ON UPDATE NO ACTION ON DELETE CASCADE;

    ALTER TABLE IF EXISTS public.scraping_jobs
        ADD CONSTRAINT fk_scraping_cuenta FOREIGN KEY (cuenta_social_id)
        REFERENCES public.cuentas_sociales (id_cuenta_social)
        ON UPDATE NO ACTION ON DELETE SET NULL;

    ALTER TABLE users ALTER COLUMN empresa_id DROP NOT NULL;

    END;

    -- 1. Primero, creamos la columna permitiendo nulos (para que no falle con los datos viejos)
ALTER TABLE public.cuentas_sociales
ADD COLUMN red_social character varying(50);

-- 2. Llenamos los registros viejos con un valor temporal válido (ej. 'instagram')
-- (Puedes cambiar 'instagram' por 'X' o 'facebook' si prefieres que los viejos sean esos)
UPDATE public.cuentas_sociales 
SET red_social = 'instagram' 
WHERE red_social IS NULL;

-- 3. Ahora que ya no hay campos vacíos, la hacemos obligatoria (NOT NULL)
ALTER TABLE public.cuentas_sociales
ALTER COLUMN red_social SET NOT NULL;

-- 4. Finalmente, le agregamos la regla de validación
ALTER TABLE public.cuentas_sociales
ADD CONSTRAINT chk_red_social CHECK (red_social IN ('instagram', 'X', 'facebook'));
